/* ==========================================================
   LUMA HOTEL - ADMIN SUPPORT
   ==========================================================

   Adds the admin flag to Accounts and creates a separate
   admin account for you to use.

   Run once, after schema.sql and sessions-migration.sql:

       mysql -u root -p hotel_reservation < admin-migration.sql

   ----------------------------------------------------------
   WHY A SEPARATE ACCOUNT

   An admin account is a normal account with one extra
   column set to TRUE. Keeping it separate from your
   customer account means you can sign in as either, and
   test that a normal customer really is blocked from the
   admin pages.
   ========================================================== */

USE hotel_reservation;

/* ----------------------------------------------------------
   1. Add the admin flag

   EXISTING ROWS get FALSE, so nobody becomes an admin by
   accident when this runs. Only the account below is
   promoted.
   ---------------------------------------------------------- */

ALTER TABLE Accounts
ADD COLUMN is_admin BOOLEAN NOT NULL DEFAULT FALSE;

/* ----------------------------------------------------------
   2. Create the admin account

   The password hash below is for: admin12345

   IMPORTANT: this is a hash we generated by hand, so treat
   it as a starting value only. If sign-in fails with it,
   register a normal account through the website and flag
   that account instead:

       UPDATE Accounts SET is_admin = TRUE WHERE email = '...';

   Anything that goes through /api/accounts gets a real
   bcrypt hash and is guaranteed to work.
   ---------------------------------------------------------- */

INSERT INTO Accounts
