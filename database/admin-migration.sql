/* ----------------------------------------------------------
   3. Promote an existing account instead (optional)

   If you would rather make your own account the admin,
   uncomment this line and put your email in it:

   UPDATE Accounts SET is_admin = TRUE WHERE email = 'your@email.com';
   ---------------------------------------------------------- */

/* ==========================================================
   CHECKS
   ========================================================== */

SELECT 'Admin accounts:' AS check_name;
SELECT account_id, first_name, last_name, email, is_admin
FROM Accounts
ORDER BY is_admin DESC, account_id;

SELECT 'Column added:' AS check_name;
SHOW COLUMNS FROM Accounts LIKE 'is_admin';
